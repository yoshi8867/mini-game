/* ══════════════════════════════════════════════════════════════════════
   룰렛 스물넷.

   칸은 셋, 확률은 고르다(각 1/3). 칸 값은 10단위다.

   2026-10-13 — 우연이 너무 크다고 해서 **칸의 퍼짐을 절반으로 줄였다.**
   기댓값은 하나도 안 바꿨다. 각 칸이 기댓값에서 떨어진 거리를 반으로 줄이고
   10단위로 맞췄다. 그래서 아래 「앞의 열」도 이제 처음 적어 준 그대로는 아니다.

   무작위로 뽑지 않고 손으로 짰다. 같은 기댓값에 분산만 다른 짝을 일부러
   여럿 넣었다 — 13.33·20.00·23.33·30.00·70.00·80.00·83.33 이 둘씩.
   「어느 쪽이 비싼가」가 아니라 「같은 값인데 왜 느낌이 다른가」를
   놓고 다투게 하려는 것이다. 그게 이 수업이다.

   받기 싫은 것 다섯에도 짝을 두었다 — -10.00 둘, -40.00 둘.

   앞의 열은 수업을 여는 사람이 직접 적어 준 것이다. 건드리지 않았다.
   ══════════════════════════════════════════════════════════════════════ */
"use strict";

/* 적어 준 것 + 「받기 싫은 것」 하나 */
const GIVEN = [
  [  10,   10,   20],      //  13.33
  [   0,   20,   20],      //  13.33
  [   0,   30,   30],      //  20.00
  [   0,   20,   30],      //  16.67
  [  30,   40,   50],      //  40.00
  [  20,   20,   20],      //  20.00
  [ -30,  -20,  -10],      // -20.00  받기 싫은 것
];

/* 기댓값을 10~100 에 고루 깔되, 둘씩 짝을 지어 분산만 벌렸다 */
const MADE = [
  [  20,   20,   30],      //  23.33
  [  10,   20,   40],      //  23.33  같은 값인데 널뛴다
  [  30,   30,   30],      //  30.00  분산 0
  [ -10,   40,   60],      //  30.00
  [  50,   50,   50],      //  50.00
  [  10,   60,   60],      //  43.33
  [  70,   70,   70],      //  70.00
  [  50,   70,   90],      //  70.00
  [ 100,  100,  100],      // 100.00
  [  50,   90,  110],      //  83.33
];

/* 2026-10-13 — 기댓값 낮은 셋(10.00 둘, 13.33 하나)을 빼고 80 언저리 셋을 넣었다.
   그 뒤 [40,100,100] 을 [70,90,90] 으로 바꿨다 — 80.00 둘, 83.33 하나 */
const HIGH = [
  [  70,   80,   90],      //  80.00
  [  60,   80,  100],      //  80.00
  [  70,   90,   90],      //  83.33
];

/* 받기 싫은 것 넷 더. 여기도 짝이 있다 */
const BAD = [
  [ -10,  -10,  -10],     // -10.00  분산 0
  [ -20,  -10,    0],     // -10.00  한 칸은 본전
  [ -40,  -40,  -40],     // -40.00
  [ -70,  -30,  -20],     // -40.00  꽝이 아주 깊다
];

const CELLS = GIVEN.concat(MADE, HIGH, BAD);

/* 기댓값. 소수 둘째 자리까지만 쓴다 */
const ev = c => (c[0] + c[1] + c[2]) / 3;
const round2 = v => Math.round(v * 100) / 100;

const WHEELS = CELLS.map((cells, i) => ({
  id: i + 1,
  cells: cells.slice(),
  ev: round2(ev(cells)),
  bad: ev(cells) < 0,                   // 받기 싫은 것 — 탈출 경매로 돈다
}));

const byId = {};
WHEELS.forEach(w => byId[w.id] = w);

/* 한 번 돌린다. 칸 셋이 고르게 나온다 */
function spin(wheel, rnd){
  const k = Math.floor((rnd === undefined ? Math.random() : rnd) * 3) % 3;
  return {at: k, got: wheel.cells[k]};
}

module.exports = {WHEELS, byId, spin, ev, round2};
